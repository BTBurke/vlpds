/// Records at the `q` quantile of repos (0 <= q <= 1), by bucket.
pub fn quantile(q: f64) -> u32 {
    let total: u64 = REAL_DIST.iter().map(|b| b.2).sum();
    let want = (q * total as f64).ceil().max(1.0) as u64;
    let mut acc = 0;
    for &(lo, hi, n) in REAL_DIST {
        acc += n;
        if acc >= want {
            return if q >= 1.0 { hi } else { lo };
        }
    }
    REAL_DIST.last().map_or(0, |b| b.1)
}

/// A draw from the distribution, given two uniform numbers in [0, 1): the
/// bucket, then a value in it.
pub fn draw(u1: f64, u2: f64) -> u32 {
    let total: u64 = REAL_DIST.iter().map(|b| b.2).sum();
    let r = ((u1 * total as f64) as u64).min(total - 1);
    let mut acc = 0;
    for &(lo, hi, n) in REAL_DIST {
        acc += n;
        if r < acc {
            return lo + ((u2 * (hi - lo + 1) as f64) as u32).min(hi - lo);
        }
    }
    0
}

